-- POVO AI Guidance: catalog and schemas.
--
-- Placeholders (substituted by scripts/deploy_schema.py):
--   ${catalog}        DATABRICKS_CATALOG      (default povo_ai_guidance)
--   ${bronze_schema}  DATABRICKS_SCHEMA       (default bronze)
--   ${app_schema}     DATABRICKS_APP_SCHEMA   (default app)
--
-- Many workspaces only let admins create catalogs. In that case ask for the
-- catalog to be pre-created and run deploy_schema.py with --skip-catalog, which
-- skips the CREATE CATALOG statement below and runs everything else.

CREATE CATALOG IF NOT EXISTS ${catalog}
COMMENT 'POVO AI Guidance: field-sales guidance app for POVO in Hidradenitis Suppurativa';

CREATE SCHEMA IF NOT EXISTS ${catalog}.${bronze_schema}
COMMENT 'Source-like reference data (territories, employees, HCPs, activity, content). Read only for the app; regenerated by the seeder.';

CREATE SCHEMA IF NOT EXISTS ${catalog}.${app_schema}
COMMENT 'Tables the app writes (calls, assessments, compliance checks, revisions, snapshots, cache, audit, job runs, brand configuration).';

-- The brand master. Created here, before the bronze and app tables, because
-- every other table's BRAND_CODE is a foreign key to it. Written by the app's
-- admin endpoints (users in ADMIN_USERS_FILE). Databricks constraints are
-- informational (not enforced); SQLite enforces the same keys.
CREATE TABLE IF NOT EXISTS ${catalog}.${app_schema}.CFG_BRAND (
  BRAND_CODE STRING NOT NULL COMMENT 'Brand key, e.g. POVO',
  BRAND_NAME STRING COMMENT 'Display name in the brand selector',
  DESCRIPTION STRING COMMENT 'What the product is; also tells the next-call AI',
  IS_ACTIVE BOOLEAN COMMENT 'False hides the brand from every user',
  SORT_ORDER INT COMMENT 'Order in the brand selector',
  UPDATED_AT TIMESTAMP COMMENT 'Last updated (UTC)',
  UPDATED_BY STRING COMMENT 'Admin username, or system',
  CONSTRAINT pk_cfg_brand PRIMARY KEY (BRAND_CODE)
) USING DELTA
COMMENT 'Brands the app serves (the brand master). A brand in DIM_SALES_ASSIGNMENT is registered here automatically. Primary key BRAND_CODE.';
