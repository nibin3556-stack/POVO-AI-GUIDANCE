-- AI Guidance: bronze reference tables (ARCHITECTURE.md section 4.1).
--
-- Keys: every table has ONE primary-key column (its first column). BRAND_CODE
-- is never part of a primary key: it is a FOREIGN KEY to the brand master
-- ${catalog}.${app_schema}.CFG_BRAND (created in 00_catalog_schemas.sql).
-- Where the natural key spans several columns, the primary key is a text ID
-- built from them, joined with "|" (e.g. GOAL_ID = POVO|NE-POR|2026-10|PEF).
-- Databricks constraints are informational (not enforced); the loader and the
-- data pipeline keep them true. SQLite enforces the same keys.
--
-- The app only reads these tables. They are loaded by the data pipeline
-- (docs/DATA_PIPELINE_TABLES.md) or regenerated by seed/generate_seed_data.py
-- and loaded by scripts/load_seed_data.py, which reads this file to learn each
-- column's type, so keep one column per line in the form
-- NAME TYPE [NOT NULL] COMMENT '...'.
-- Only the three fact tables are clustered: they are the only ones queried by
-- territory at volume, and the rest are a few hundred rows at most.

